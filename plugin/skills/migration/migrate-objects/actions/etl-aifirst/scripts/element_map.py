#!/usr/bin/env python3
"""ELEMENT MAP -- which source element each generated model came from, who wrote it, and where the
element sits in the source document.

WHY THIS EXISTS. A repair after a failed data comparison has to know, for the model it is about to
touch, (a) which source element that model stands for, (b) whether SnowConvert's translators wrote it
(tier 1), the engine wrote it around a model-supplied payload (tier 2, `SSC-AI-ASSISTED`) or a model
wrote it outright (tier 3, `SSC-AI-AUTHORED`), and (c) the element's own lines in the source document.
Tier decides what a repair may do: a tier-1 model is regenerated by the next convert, so a hand edit
is lost and hides an engine defect; a tier-3 model has no generator and is edited in place. Before
this file, tier lived only in a header comment and the element only in the model name.

WHAT IS READ, NOTHING INFERRED BEYOND IT.
  - elements: the source document, located through the platform table's `naming_policy.name_source`
    (`transform/name/text()`, `component/@name`, `node/elementParameter[@name=X]/@value`). Each match
    is one element: its name, its kind (`<type>` child or `@kind`/`@componentName` attribute when the
    element states one) and its 1-based inclusive line range. A document that is not XML, or a
    name_source this reader does not parse, yields no elements and says so (`elements_from`).
  - models: every `models/**/*.sql` under the emitted dbt project(s). Tier from the header marker;
    the source element from a tier-2/3 header's `Source element :` line, else by the table's own
    model-naming normalisation (emit.Emitter._normalise) against each element name, allowing the
    layer prefixes the emitter writes (`int_`, `stg_<source>__`).
A model that matches no element keeps `source_element: null` -- never a guess.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
import xml.parsers.expat
from pathlib import Path

SCHEMA = "aim.element-map.v1"
_TIER_MARKERS = (("SSC-AI-AUTHORED", 3), ("SSC-AI-ASSISTED", 2))
_SOURCE_ELEMENT_RE = re.compile(r"^--\s*Source element\s*:\s*(.+?)\s*$", re.MULTILINE)
_HEADER_LINES = 12


def _parse_name_source(name_source: str):
    """`transform/name/text()` -> ('transform', 'child', 'name', None);
    `component/@name` -> ('component', 'attr', 'name', None);
    `node/elementParameter[@name=UNIQUE_NAME]/@value` -> ('node', 'param', 'elementParameter',
    ('name', 'UNIQUE_NAME', 'value')). Anything else -> None."""
    text = (name_source or "").split(" ", 1)[0].strip()
    m = re.fullmatch(r"(\w+)/(\w+)/text\(\)", text)
    if m:
        return m.group(1), "child", m.group(2), None
    m = re.fullmatch(r"(\w+)/@(\w+)", text)
    if m:
        return m.group(1), "attr", m.group(2), None
    m = re.fullmatch(r"(\w+)/(\w+)\[@(\w+)='?([^'\]]+)'?\]/@(\w+)", text)
    if m:
        return m.group(1), "param", m.group(2), (m.group(3), m.group(4), m.group(5))
    return None


def document_elements(document: str, name_source: str) -> tuple[list[dict], str]:
    """Every element the name_source names, with kind and line range. Returns (elements, how)."""
    spec = _parse_name_source(name_source)
    if spec is None:
        return [], f"name_source {name_source!r} is not a form this reader parses"
    tag, mode, child_or_attr, param = spec
    parser = xml.parsers.expat.ParserCreate()
    stack: list[dict] = []
    found: list[dict] = []

    def start(name, attrs):
        node = {"tag": name, "attrs": attrs, "start": parser.CurrentLineNumber, "text": [], "children": {}}
        if stack:
            parent = stack[-1]
            if name == child_or_attr and mode == "child":
                parent["_capture"] = node
            if mode == "param" and name == child_or_attr and attrs.get(param[0]) == param[1]:
                parent["name"] = attrs.get(param[2], "")
        stack.append(node)
        if name == tag and mode == "attr":
            node["name"] = attrs.get(child_or_attr, "")

    def chars(data):
        if stack:
            stack[-1]["text"].append(data)

    def end(name):
        node = stack.pop()
        text = "".join(node["text"]).strip()
        if stack:
            parent = stack[-1]
            if parent.get("_capture") is node:
                parent["name"] = text
            if name == "type" and "kind" not in parent:
                parent["kind"] = text
        if name == tag and node.get("name"):
            kind = node.get("kind") or node["attrs"].get("kind") or node["attrs"].get("componentName") or ""
            found.append({"element_id": node["name"], "kind": kind,
                          "source_lines": [node["start"], parser.CurrentLineNumber]})

    parser.StartElementHandler = start
    parser.EndElementHandler = end
    parser.CharacterDataHandler = chars
    try:
        with open(document, "rb") as fh:
            parser.ParseFile(fh)
    except (OSError, xml.parsers.expat.ExpatError) as exc:
        return [], f"document not readable as XML: {exc}"
    return found, f"source document, {name_source}"


def _normaliser(table: dict):
    here = os.path.dirname(os.path.abspath(__file__))
    if here not in sys.path:
        sys.path.insert(0, here)
    from emit import Emitter  # noqa: PLC0415 - emit pulls the emitter's own imports; only needed here

    policy = table.get("naming_policy") or {}
    return lambda name: Emitter._normalise(name, policy)


def _model_tier(head: str) -> tuple[int, str | None]:
    for marker, tier in _TIER_MARKERS:
        if marker in head:
            return tier, marker
    return 1, None


def _match_element(stem: str, by_norm: dict[str, str]) -> str | None:
    if stem in by_norm:
        return by_norm[stem]
    for prefix_end in ("int_", "stg_"):
        if stem.startswith(prefix_end) and stem[len(prefix_end):] in by_norm:
            return by_norm[stem[len(prefix_end):]]
    if "__" in stem and stem.startswith("stg_"):
        tail = stem.split("__", 1)[1]
        if tail in by_norm:
            return by_norm[tail]
    return None


def build(table: dict, document: str, package_dir: str) -> dict:
    policy = table.get("naming_policy") or {}
    elements, how = document_elements(document, policy.get("name_source", ""))
    normalise = _normaliser(table)
    by_norm: dict[str, str] = {}
    for el in elements:
        by_norm.setdefault(normalise(el["element_id"]), el["element_id"])
    lines_of = {el["element_id"]: el["source_lines"] for el in elements}

    models = []
    root = Path(package_dir)
    for sql in sorted(root.glob("*/models/**/*.sql")):
        rel = sql.relative_to(root).as_posix()
        if "/target/" in f"/{rel}" or "/dbt_packages/" in f"/{rel}":
            continue
        head = "\n".join(sql.read_text(encoding="utf-8", errors="replace").splitlines()[:_HEADER_LINES])
        tier, marker = _model_tier(head)
        stated = _SOURCE_ELEMENT_RE.search(head) if tier > 1 else None
        element = stated.group(1) if stated else _match_element(sql.stem, by_norm)
        models.append({
            "model": sql.stem,
            "path": rel,
            "tier": tier,
            "tier_marker": marker,
            "source_element": element,
            "source_element_from": ("header" if stated else "model name") if element else None,
            "source_lines": lines_of.get(element) if element else None,
        })
    return {
        "schema": SCHEMA,
        "document": os.path.basename(document),
        "platform": table.get("platform"),
        "elements_from": how,
        "elements": elements,
        "models": models,
    }


def cur_extension(map_path: str, package_root: str) -> dict:
    """The unit's `extensions.aiFirst` value: where the map is, and per model its tier, source element
    and lines, with the model's project-relative path. Read by validateEtlRepair."""
    data = json.loads(Path(map_path).read_text(encoding="utf-8"))
    models = {}
    for m in data.get("models", []) or []:
        models[m["model"]] = {
            "path": f"{package_root.rstrip('/')}/{m['path']}",
            "tier": m["tier"],
            "sourceElement": m.get("source_element"),
            "sourceLines": m.get("source_lines"),
        }
    return {"elementMap": map_path, "models": models}


def main(argv: list[str]) -> int:
    if argv[:1] == ["--cur-extension"]:
        ap = argparse.ArgumentParser(prog="element_map.py --cur-extension")
        ap.add_argument("map", help="project-relative reports/AiFirstElementMap/<PACKAGE>/element_map.json")
        ap.add_argument("--package-root", required=True, help="snowflake/_etl/<PACKAGE>")
        args = ap.parse_args(argv[1:])
        print(json.dumps(cur_extension(args.map, args.package_root), sort_keys=True))
        return 0
    ap = argparse.ArgumentParser(prog="element_map.py", description=__doc__.splitlines()[0])
    ap.add_argument("table", help="platform table json")
    ap.add_argument("document", help="source document that was migrated")
    ap.add_argument("output_root", help="the migration's $OUT directory")
    args = ap.parse_args(argv)
    table = json.loads(Path(args.table).read_text(encoding="utf-8"))
    etl = Path(args.output_root) / "Output" / "ETL"
    packages = [p for p in sorted(etl.iterdir()) if p.is_dir() and p.name != "etl_configuration"] if etl.is_dir() else []
    if len(packages) != 1:
        print(f" element map       : UNMEASURED, expected one package under {etl}, found {len(packages)}")
        return 1
    result = build(table, args.document, str(packages[0]))
    result["package"] = packages[0].name
    out = Path(args.output_root) / "Reports" / "AiFirstElementMap" / "element_map.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(result, indent=1) + "\n", encoding="utf-8")
    tiers = {}
    for m in result["models"]:
        tiers[m["tier"]] = tiers.get(m["tier"], 0) + 1
    unmatched = sum(1 for m in result["models"] if not m["source_element"])
    print(f" element map       : {len(result['elements'])} element(s), {len(result['models'])} model(s) "
          f"(tier {', tier '.join(f'{t}: {n}' for t, n in sorted(tiers.items())) or '-'}; "
          f"{unmatched} with no source element) written to {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
